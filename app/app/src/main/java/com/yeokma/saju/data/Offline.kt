package com.yeokma.saju.data

/**
 * 서버가 꺼져 있을 때 보여 줄 목업 풀이. 만세력 계산은 서버에 있으므로 여기서는 태어난 달의 계절 기운만 쓴다.
 * 서버를 켜면 정밀 만세력과 LLM(또는 서버 목업) 풀이로 바뀐다.
 */
object Offline {
    private fun season(birth: String): Pair<String, String> {
        val m = birth.split('.').getOrNull(1)?.toIntOrNull() ?: 1
        return when (m) {
            2, 3, 4 -> "목" to "곧게 자라려는 나무"
            5, 6, 7 -> "화" to "환하게 번지는 불"
            8, 9, 10 -> "금" to "단단하게 벼려진 쇠"
            else -> "수" to "어디로든 스며드는 물"
        }
    }

    fun report(p: Profile, worry: String): Report {
        val name = p.name.ifBlank { "손님" }
        val (el, nature) = season(p.birth)
        val w = worry.take(40)
        return Report(
            "${name}님, 이번 고민은 생각보다 잘 풀려요",
            listOf(
                "이런 마음, 요즘 자주 드시죠?" to "\"$w\" 이런 생각이 들면 몸보다 마음이 먼저 바빠지죠. 가는 길에 할 말을 몇 번이고 되뇌다가, 막상 도착하면 준비한 말이 하얗게 지워질까 봐 걱정되셨을 거예요. 그런데 이 떨림은 자신이 없어서가 아니에요. 이 일을 그만큼 아끼고 있어서 생기는 거예요. 지금 차 안에 앉아 계신 이 몇 분이, 그 마음을 정리하기에 딱 좋은 시간이에요.",
                "태어난 계절의 기운" to "${name}님은 $el 기운이 강한 계절에 태어나셨어요. ${nature}처럼, 한번 마음먹은 일에는 끝까지 밀고 나가는 힘이 있는 분이에요. 대신 마음이 앞서 나가면 말이 빨라지고 생각이 흩어지기 쉬워요. 오늘은 속도만 붙잡으면 됩니다.",
                "역마아씨의 예언" to "자, 예언 하나 드릴게요. 이런 사주는 첫 장면에서 늘 한 번 흔들려요. 그러니 오늘도 처음 몇 초는 조금 어색할 거예요. 그런데 그다음이 재밌어요. 두 번째 대화에서 상대가 고개를 끄덕이는 순간이 오고, 그때부터 분위기가 ${name}님 쪽으로 확 넘어옵니다. 돌아오는 길에 \"생각보다 괜찮았네\" 하고 혼자 웃게 되실 거예요. 이 예언이 그대로 맞게 하려면 딱 하나만 하세요. 차에서 내리기 전에 숨을 네 번 천천히 쉬고, 오늘 꼭 전하고 싶은 한 문장을 소리 내 말해 보는 거예요. 잘 다녀오세요.",
            ),
        )
    }
}
