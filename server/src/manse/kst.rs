//! 한국 표준시 이력과 서머타임. 출생 당시의 시계 시각을 UT로 바꾼다.
//! 출처: IANA tz 데이터베이스 Asia/Seoul (기억에 의존한 값이라 경계일은 다시 확인 필요)

/// (시작, 끝(포함 안 함)) yyyymmdd, UTC 오프셋(분)
const STANDARD: &[(u32, u32, i32)] = &[
    (0, 19080401, 507),           // 지방 평균시 (서울 127°E 근사)
    (19080401, 19120101, 510),    // UTC+8:30
    (19120101, 19540321, 540),    // UTC+9
    (19540321, 19610810, 510),    // UTC+8:30
    (19610810, 99999999, 540),    // UTC+9
];

/// 서머타임(+60분) 구간 (yyyymmdd, 포함 시작 ~ 포함 안 함 끝)
const DST: &[(u32, u32)] = &[
    (19480601, 19480913), (19490403, 19490911), (19500401, 19500910), (19510506, 19510909),
    (19550505, 19550909), (19560520, 19560930), (19570505, 19570922), (19580504, 19580921),
    (19590503, 19590920), (19600501, 19600918), (19870510, 19871011), (19880508, 19881009),
];

pub struct Offset { pub minutes: i32, pub dst: bool, pub label: &'static str }

pub fn offset(ymd: u32) -> Offset {
    let std = STANDARD.iter().find(|(a, b, _)| ymd >= *a && ymd < *b).map(|x| x.2).unwrap_or(540);
    let dst = DST.iter().any(|(a, b)| ymd >= *a && ymd < *b);
    let label = match std { 507 => "지방 평균시", 510 => "UTC+8:30", _ => "UTC+9" };
    Offset { minutes: std + if dst { 60 } else { 0 }, dst, label }
}
